def topic(name: str) -> tuple:
    title, rows = _TOPICS.get(name, ("📖 راهنما", ["این موضوع پیدا نشد."]))
    buttons = [
        [Button.inline("📖 فهرست راهنما", b"help")],
        [Button.inline("🆘 پشتیبانی", b"support"),
         Button.inline("🏠 منوی اصلی", b"home")],
    ]
    return cards.card(title, rows), buttons


def topics() -> list:
    return sorted(_TOPICS)
